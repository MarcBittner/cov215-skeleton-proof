import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join, relative } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, "..", "..", "..")

export const SCHEMA_FILES = {
  runRequestSchema: "scripts/e2e/contract/run-request.schema.json",
  reportRequestSchema: "scripts/e2e/contract/report-request.schema.json",
  setupPlanSchema: "scripts/e2e/contract/setup-plan.schema.json",
  shardPlanSchema: "scripts/e2e/contract/shard-plan.schema.json",
  bundleSchema: "scripts/e2e/contract/bundle.schema.json",
  bundleEnvelopeSchema: "scripts/e2e/contract/bundle-envelope.schema.json",
  controlSchema: "scripts/e2e/contract/control.schema.json",
  commentRowsSchema: "scripts/e2e/contract/comment-rows.schema.json",
  selectionSchema: "scripts/e2e/select/selection.schema.json",
  runRecordSchema: "scripts/e2e/measure/run.schema.json",
  manifestSchema: "e2e/map/manifest.schema.json",
  manifestIndexSchema: "e2e/map/manifest-index.schema.json",
}

export const SCHEMA_CONSTANTS = [
  { schema: "bundleSchema", path: ["properties", "tenants", "maxProperties"], constant: "MAX_RUN_TENANTS" },
  { schema: "controlSchema", path: ["properties", "created", "properties", "tenants", "maxItems"], constant: "MAX_RUN_TENANTS" },
  { schema: "controlSchema", path: ["properties", "limiter", "properties", "max_tenants", "maximum"], constant: "MAX_RUN_TENANTS" },
  { schema: "setupPlanSchema", path: ["properties", "tenants", "maxItems"], constant: "MAX_RUN_TENANTS" },
  { schema: "controlSchema", path: ["properties", "created", "properties", "users", "maxItems"], constant: "MAX_RUN_USERS" },
  { schema: "controlSchema", path: ["properties", "limiter", "properties", "max_users", "maximum"], constant: "MAX_RUN_USERS" },
]

export function contractConstants(source = readFileSync(join(here, "constants.ts"), "utf8")) {
  const out = {}
  for (const m of source.matchAll(/^export const ([A-Z][A-Z0-9_]*) = (\d+)$/gm)) out[m[1]] = Number(m[2])
  return out
}

export function constantDrift(schemas, constants = contractConstants()) {
  const errors = []
  for (const pin of SCHEMA_CONSTANTS) {
    const want = constants[pin.constant]
    if (typeof want !== "number") {
      errors.push(`${pin.constant} is not a numeric export of constants.ts`)
      continue
    }
    const got = pin.path.reduce((o, k) => (o && typeof o === "object" ? o[k] : undefined), schemas[pin.schema])
    if (got !== want) errors.push(`${SCHEMA_FILES[pin.schema]} ${pin.path.join(".")} is ${got}, constants.ts ${pin.constant} is ${want}`)
  }
  return errors
}

export function render() {
  const lines = [
    `// Generated by scripts/e2e/contract/gen-schemas.mjs from the .schema.json files. Do not edit.`,
    `import type { JsonSchema } from "./validate.js"`,
    ``,
  ]
  const schemas = {}
  for (const [name, file] of Object.entries(SCHEMA_FILES)) {
    schemas[name] = JSON.parse(readFileSync(join(root, file), "utf8"))
    lines.push(`export const ${name}: JsonSchema = ${JSON.stringify(schemas[name])}`, ``)
  }
  const drift = constantDrift(schemas)
  if (drift.length > 0) throw new Error(`schema caps disagree with constants.ts:\n${drift.join("\n")}`)
  lines.push(
    `export const SCHEMA_FILES = ${JSON.stringify(SCHEMA_FILES, null, 2)} as const`,
    ``,
  )
  return lines.join("\n")
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = join(here, "schemas.generated.ts")
  writeFileSync(out, render())
  process.stdout.write(`wrote ${relative(root, out)}\n`)
}
